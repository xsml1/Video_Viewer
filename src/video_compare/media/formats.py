def media_file_filter(media_kind: str) -> str:
    suffixes = IMAGE_SUFFIXES if media_kind == "image" else VIDEO_SUFFIXES
    label = "图像" if media_kind == "image" else "视频"
    return f"{label} ({' '.join(f'*.{suffix}' for suffix in suffixes)});;所有文件 (*)"
